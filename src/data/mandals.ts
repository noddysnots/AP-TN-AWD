export interface Mandal {
  name: string
  district: string
  state: 'TG' | 'AP'
}

/**
 * Normalized keys for matching GeoJSON district labels to `mandals.ts` `district` values.
 * Lowercase, collapse spaces, strip punctuation.
 */
export function normalizeDistrictForMandals(s: string): string {
  return s
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/[^a-z0-9 ]/g, '')
    .trim()
}

