export function resolveDistrictName(raw: string, state: 'AP' | 'TG'): string {
  void state
  const n = normalizeDistrictForMandals(raw)
  const alias = DISTRICT_ALIASES[n]
  return alias || raw.trim()
}

export function getMandalsForDistrict(districtName: string, state: 'AP' | 'TG'): Mandal[] {
  const resolved = resolveDistrictName(districtName, state)
  const key = normalizeDistrictForMandals(resolved)
  return MANDALS.filter(
    (m) => m.state === state && normalizeDistrictForMandals(m.district) === key,
  ).sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: 'base' }))
}

