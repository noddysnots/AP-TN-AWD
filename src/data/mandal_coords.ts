export const getMandalCoords = (
  mandalName: string,
  district: string,
  state: 'AP' | 'TG'
): { lat: number; lon: number } | null => {
  const normalize = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
  const normName = normalize(mandalName);
  const normDist = normalize(district);

  // Pass 1: exact match on both name and district
  let entry = MANDAL_COORDS.find(m =>
    m.state === state &&
    normalize(m.name) === normName &&
    normalize(m.district) === normDist
  );
  if (entry) return { lat: entry.lat, lon: entry.lon };

  const nameBase = (n: string) => n.replace(/\d+$/, '');

  // Pass 1b: same district + state, mandal names equal ignoring trailing digits (e.g. Kandukur vs Kandukur2)
  const flexKey = nameBase(normName);
  if (flexKey.length > 0) {
    const flexHits = MANDAL_COORDS.filter(
      (m) =>
        m.state === state &&
        normalize(m.district) === normDist &&
        nameBase(normalize(m.name)) === flexKey,
    );
    if (flexHits.length === 1) return { lat: flexHits[0].lat, lon: flexHits[0].lon };
    if (flexHits.length > 1) {
      const exactFlex = flexHits.find((m) => normalize(m.name) === normName);
      if (exactFlex) return { lat: exactFlex.lat, lon: exactFlex.lon };
    }
  }

  // Pass 2: name match only (handles district name spelling variants)
  const nameMatches = MANDAL_COORDS.filter(m =>
    m.state === state && normalize(m.name) === normName
  );
  if (nameMatches.length === 1) {
    const only = nameMatches[0];
    if (normalize(only.district) === normDist) return { lat: only.lat, lon: only.lon };
    return null;
  }
  if (nameMatches.length > 1) {
    const sameDist = nameMatches.find((m2) => normalize(m2.district) === normDist);
    if (sameDist) return { lat: sameDist.lat, lon: sameDist.lon };
    const partial = nameMatches.find(
      (m2) =>
        normalize(m2.district).includes(normDist.slice(0, 6)) ||
        normDist.includes(normalize(m2.district).slice(0, 6)),
    );
    if (partial) return { lat: partial.lat, lon: partial.lon };
    return null;
  }

  return null;
};
